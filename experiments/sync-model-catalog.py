# Synchronize pinned catalogue additions, retaining older aliases absent upstream.
import json, re
from pathlib import Path
catalog = json.loads(Path('docs/case-studies/issue-50/data/model-catalog.json').read_text())
Path('js/src/tools/model-catalog.mjs').write_text('// Hive Mind bundled catalogue; provenance: docs/case-studies/issue-50.\n// Updated by experiments/sync-model-catalog.py. Native CLIs validate availability.\nexport const syncedModels = ' + json.dumps(catalog['models'], indent=2) + ';\nexport const syncedDefaults = ' + json.dumps(catalog['defaults'], indent=2) + ';\n')
for tool, models in catalog['models'].items():
    path = Path('js/src/tools/' + tool + '.mjs')
    source = path.read_text()
    start = source.index('export const modelMap = {')
    end = source.index('\n};', start) + 3
    entries = re.findall(r"(?m)^\s*(?:['\"]([^'\"]+)['\"]|(\w+)):\s*['\"]([^'\"]+)['\"]", source[start:end])
    legacy = {(quoted or bare): value for quoted, bare, value in entries if (quoted or bare) not in models}
    replacement = 'export const modelMap = {\n' + ''.join('  ' + json.dumps(key) + ': ' + json.dumps(value) + ',\n' for key, value in legacy.items()) + '  ...syncedModels.' + tool + ',\n};'
    source = source[:start] + replacement + source[end:]
    if "from './model-catalog.mjs'" not in source:
        source = "import { syncedModels, syncedDefaults } from './model-catalog.mjs';\n" + source
    source = re.sub(r"defaultModel: '[^']+'[^\n]*", 'defaultModel: syncedDefaults.' + tool + ',', source)
    path.write_text(source)
    path = Path('rust/src/tools/' + tool + '.rs')
    source = path.read_text()
    start = source.index('    let mut map = HashMap::new();')
    end = source.index('\n    map\n', start)
    entries = re.findall(r'map.insert\(\s*"([^"]+)",\s*"([^"]+)"\s*,?\s*\);', source[start:end])
    legacy = {key: value for key, value in entries if key not in models}
    replacement = '    let mut map = HashMap::new();\n    // Pinned Hive Mind catalogue; generated by experiments/sync-model-catalog.py.\n'
    replacement += ''.join('    map.insert(' + json.dumps(key) + ', ' + json.dumps(value) + ');\n' for key, value in (legacy | models).items())
    source = source[:start] + replacement.rstrip() + source[end:]
    source = re.sub(r'default_model: "[^"]+"[^\n]*', 'default_model: ' + json.dumps(catalog['defaults'][tool]) + ',', source)
    path.write_text(source)

Path('rust/tests/fixtures').mkdir(parents=True, exist_ok=True)
Path('rust/tests/fixtures/model-catalog.json').write_text(Path('docs/case-studies/issue-50/data/model-catalog.json').read_text())
